export function normalizeSupportLocale(value) {
  const locale = String(value || "").toLowerCase();
  if (locale.startsWith("uk")) return "uk";
  if (locale.startsWith("ru")) return "ru";
  return "en";
}

function tokenize(value) {
  return String(value || "")
    .toLowerCase()
    .replace(/[^a-zа-яёіїєґ0-9]+/giu, " ")
    .split(/s+/)
    .filter((token) => token.length >= 2);
}

export function rankSupportFaq(query, locale = "en", limit = 6) {
  const lang = normalizeSupportLocale(locale);
  const queryTokens = new Set(tokenize(query));

  return SUPPORT_FAQ.map((faq) => {
    const localized = faq.copy[lang] || faq.copy.en;
    const source = [
      localized.question,
      localized.answer,
      ...(faq.keywords || []),
    ].join(" ");

    const sourceTokens = new Set(tokenize(source));
    let score = 0;

    for (const token of queryTokens) {
      if (sourceTokens.has(token)) score += 3;
      if ((faq.keywords || []).some((keyword) =>
        String(keyword).toLowerCase().includes(token)
      )) {
        score += 2;
      }
    }

    const normalizedQuery = String(query || "").trim().toLowerCase();
    if (
      normalizedQuery &&
      String(localized.question).toLowerCase().includes(normalizedQuery)
    ) {
      score += 12;
    }

    return { faq, score };
  })
    .filter((item) => item.score > 0)
    .sort((a, b) =>
      b.score - a.score ||
      (b.faq.priority || 0) - (a.faq.priority || 0)
    )
    .slice(0, Math.max(1, limit));
}

export function getLocalizedFaq(locale = "en") {
  const lang = normalizeSupportLocale(locale);
  return SUPPORT_FAQ
    .slice()
    .sort((a, b) => (b.priority || 0) - (a.priority || 0))
    .map((faq) => ({
      id: faq.id,
      category: faq.category,
      question: (faq.copy[lang] || faq.copy.en).question,
      answer: (faq.copy[lang] || faq.copy.en).answer,
    }));
}
